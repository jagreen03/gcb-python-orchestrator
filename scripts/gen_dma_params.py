#!/usr/bin/env python3
"""Generate the GDDR7 tensor-operand DMA's SystemVerilog parameter package and
CSR wrapper from a single YAML source.

Governing doctrine: gcb-wiki/10_open_source_eda_toolchain.md sec. 3 -
"parameterisation is Jinja2 templating -> pure SystemVerilog; nothing sits
between the generator and the SV that is taped out." No Chisel / Amaranth / HDL
DSL. Precedent: gcb-spec/regen.py.

Source of truth : scripts/dma_params.yaml   (gcb-wiki/11 sec. 0 + sec. 7)
Templates       : scripts/templates/*.sv.j2
Outputs (committed, DO NOT EDIT):
    gcb-wdm-transceiver/rtl/generated/gcb_tensor_dma_params_pkg.sv
    gcb-wdm-transceiver/rtl/generated/gcb_tensor_dma_csr_wrapper.sv

Usage
-----
    python gen_dma_params.py                 # regenerate in place
    python gen_dma_params.py --check         # CI: exit 1 if any output is stale
    python gen_dma_params.py --out-dir /tmp  # write elsewhere (spot check)
    python gen_dma_params.py --print params  # dump one rendered file to stdout

Exit codes: 0 ok; 1 stale (--check) or error.
"""

from __future__ import annotations

import argparse
import math
import sys
from pathlib import Path

try:
    import yaml
except ImportError:  # pragma: no cover
    sys.exit("PyYAML required:  pip install pyyaml")

try:
    from jinja2 import Environment, FileSystemLoader, StrictUndefined
except ImportError:  # pragma: no cover
    sys.exit("Jinja2 required:  pip install jinja2")

SCRIPT_DIR = Path(__file__).resolve().parent
TEMPLATE_DIR = SCRIPT_DIR / "templates"
SOURCE_DEFAULT = SCRIPT_DIR / "dma_params.yaml"

# scripts/ -> gcb-python-orchestrator/ -> <checkout root that also holds gcb-wdm-transceiver>
CHECKOUT_ROOT = SCRIPT_DIR.parents[1]
OUT_DIR_DEFAULT = CHECKOUT_ROOT / "gcb-wdm-transceiver" / "rtl" / "generated"

BANNER_FMT = "DO NOT EDIT - generated by scripts/gen_dma_params.py from scripts/dma_params.yaml"

# The arbiter's public parameter contract (gcb_tensor_dma_arbiter port #()),
# in declaration order. Every name resolves in the evaluated namespace below.
ARBITER_PARAMS = [
    "EA_W", "OPERAND_BITS", "K_MAX", "VEC_BYTES", "VEC_W", "GRID_DIM",
    "K_STEPS", "N_TILE", "M_BANDS", "N_PASSES", "ROW_STRIDE", "BURST_BYTES",
    "MEM_DATA_W", "N_BG", "CSR_ADDR_W",
]

# file key -> (template, output filename)
TARGETS = {
    "params":  ("gcb_tensor_dma_params_pkg.sv.j2",  "gcb_tensor_dma_params_pkg.sv"),
    "wrapper": ("gcb_tensor_dma_csr_wrapper.sv.j2", "gcb_tensor_dma_csr_wrapper.sv"),
}


# ---------------------------------------------------------------------------
# source evaluation
# ---------------------------------------------------------------------------

def _clog2(n: int) -> int:
    """SystemVerilog $clog2 semantics: clog2(1) == 0, clog2(0) == 0."""
    return 0 if n <= 1 else math.ceil(math.log2(n))


def _width(n: int) -> int:
    """Width the RTL uses for an index into 0..n-1: 1 when n <= 1, else clog2(n)."""
    return 1 if n <= 1 else _clog2(n)


def _expr_env(ns: dict) -> dict:
    env = {"clog2": _clog2, "width": _width, "__builtins__": {}}
    env.update(ns)
    return env


def evaluate(src: dict) -> dict:
    """Return the flat name->int namespace: independent params, then derived
    (in file order, each a pure function of what precedes it)."""
    ns: dict[str, int] = {}
    for name, spec in src["parameters"].items():
        ns[name] = int(spec["value"])
    for d in src["derived"]:
        try:
            ns[d["name"]] = int(eval(d["expr"], _expr_env(ns)))  # noqa: S307 - controlled source
        except Exception as exc:  # pragma: no cover
            raise SystemExit(f"derived {d['name']!r}: {d['expr']!r} -> {exc}")
    return ns


def _sv_cond(py_expr: str) -> str:
    """Translate a Python bool expression from the source into an SV condition.
    The source uses only // , 'and', 'or', 'not' beyond common operators."""
    return (py_expr
            .replace(" // ", " / ")
            .replace(" and ", " && ")
            .replace(" or ", " || ")
            .replace("not ", "!"))


def check_asserts(src: dict, ns: dict) -> None:
    """Fail generation early if the source geometry is self-inconsistent -
    the same guards the emitted package will assert at elaboration."""
    bad = []
    for a in src.get("asserts", []):
        if not bool(eval(a["expr"], _expr_env(ns))):  # noqa: S307
            bad.append(f"{a['msg']}  ({a['expr']})")
    if bad:
        raise SystemExit("dma_params.yaml is self-inconsistent:\n  - " + "\n  - ".join(bad))


def _spec_version_bcd(ver: str) -> str:
    """'1.0' -> '00000100' (two BCD hex digits per dotted field)."""
    parts = (ver.split(".") + ["0", "0"])[:4]
    return "".join(f"{int(p):02X}" for p in parts)


# ---------------------------------------------------------------------------
# rendering
# ---------------------------------------------------------------------------

def build_context(src: dict) -> dict:
    ns = evaluate(src)
    check_asserts(src, ns)

    mirror = []
    for m in src["csr"]["mirror"]:
        val = m["value"] if "value" in m else ns[m["value_from"]]
        mirror.append({"name": m["name"], "offset": int(m["offset"]), "value": int(val)})

    return {
        "banner": BANNER_FMT,
        "module": src["meta"]["module"],
        "spec_version": src["meta"]["spec_version"],
        "spec_version_bcd": _spec_version_bcd(src["meta"]["spec_version"]),
        "csr_addr_w": ns["CSR_ADDR_W"],
        "parameters": [
            {"name": n, "value": ns[n], "doc": s.get("doc", "")}
            for n, s in src["parameters"].items()
        ],
        "derived": [
            {"name": d["name"], "value": ns[d["name"]], "doc": d.get("doc", "")}
            for d in src["derived"]
        ],
        "asserts": [
            {"sv_cond": _sv_cond(a["expr"]), "msg": a["msg"]}
            for a in src.get("asserts", [])
        ],
        "mirror": mirror,
        "arb_params": [{"name": p} for p in ARBITER_PARAMS],
    }


def render(env: Environment, template: str, ctx: dict) -> str:
    text = env.get_template(template).render(**ctx)
    if not text.endswith("\n"):
        text += "\n"
    return text


# ---------------------------------------------------------------------------
# driver
# ---------------------------------------------------------------------------

def main() -> int:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--source", type=Path, default=SOURCE_DEFAULT,
                    help=f"YAML source of truth (default: {SOURCE_DEFAULT.name})")
    ap.add_argument("--out-dir", type=Path, default=OUT_DIR_DEFAULT,
                    help=f"destination for the generated .sv (default: {OUT_DIR_DEFAULT})")
    ap.add_argument("--check", action="store_true",
                    help="do not write; exit 1 if any committed output differs")
    ap.add_argument("--print", dest="print_target", choices=sorted(TARGETS),
                    help="render one target to stdout and exit")
    args = ap.parse_args()

    if not args.source.exists():
        print(f"error: source not found: {args.source}", file=sys.stderr)
        return 1

    src = yaml.safe_load(args.source.read_text(encoding="utf-8"))
    try:
        ctx = build_context(src)
    except SystemExit as exc:
        print(exc, file=sys.stderr)
        return 1

    env = Environment(
        loader=FileSystemLoader(str(TEMPLATE_DIR)),
        undefined=StrictUndefined,
        keep_trailing_newline=True,
        trim_blocks=False,
        lstrip_blocks=False,
    )

    if args.print_target:
        template, _ = TARGETS[args.print_target]
        sys.stdout.write(render(env, template, ctx))
        return 0

    rc = 0
    for key, (template, filename) in TARGETS.items():
        text = render(env, template, ctx)
        dest = args.out_dir / filename
        if args.check:
            if not dest.exists():
                print(f"STALE  {dest} does not exist", file=sys.stderr)
                rc = 1
            elif dest.read_text(encoding="utf-8") != text:
                print(f"STALE  {dest} differs from {args.source.name} + template", file=sys.stderr)
                rc = 1
            else:
                print(f"ok     {dest}")
        else:
            dest.parent.mkdir(parents=True, exist_ok=True)
            existing = dest.read_text(encoding="utf-8") if dest.exists() else None
            dest.write_text(text, encoding="utf-8", newline="\n")
            print(f"{'wrote ' if existing != text else 'ok    '} {dest}")

    if args.check and rc:
        print("\nrun:  python scripts/gen_dma_params.py   then commit the result", file=sys.stderr)
    return rc


if __name__ == "__main__":
    sys.exit(main())
